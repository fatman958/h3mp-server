#!/usr/bin/env python3
"""Classify every upstream ServerHandle method to plan what a dedicated server must implement.

Usage: python3 tools/analyze-handlers.py <path/to/H3MP/src/networking> [out.md]

Reads Server.cs (positional handler table: element i == ClientPackets value i), Packet.cs (enum names)
and ServerHandle.cs (bodies), then buckets handlers by what they touch.
"""
import re, sys, pathlib, collections

net = pathlib.Path(sys.argv[1])
out = pathlib.Path(sys.argv[2] if len(sys.argv) > 2 else "docs/HANDLER_ANALYSIS.md")
rd = lambda n: (net / n).read_text(encoding="utf-8-sig")

# ---- ClientPackets enum: index -> name
pk = rd("Packet.cs")
body = pk[pk.index("public enum ClientPackets"):]
body = body[:body.index("}")]
enum = {int(v): n for n, v in re.findall(r"^\s*(\w+)\s*=\s*(\d+)", body, re.M)}

# ---- positional handler table
srv = rd("Server.cs")
tbl = srv[srv.index("packetHandlers = new PacketHandler[]"):]
tbl = tbl[tbl.index("{") + 1: tbl.index("};")]
tbl = re.sub(r"//[^\n]*", "", tbl)
entries = [e.strip() for e in tbl.split(",") if e.strip()]
table = {i: (None if e == "null" else e.split(".")[-1]) for i, e in enumerate(entries)}

# ---- handler bodies (brace matching)
sh = rd("ServerHandle.cs")
def method_body(name):
    m = re.search(r"public static void %s\s*\(int clientID, Packet packet\)\s*\{" % re.escape(name), sh)
    if not m: return None
    i, depth = m.end(), 1
    while depth and i < len(sh):
        depth += (sh[i] == "{") - (sh[i] == "}")
        i += 1
    return sh[m.end(): i - 1]

IMPLEMENTED = {"welcomeReceived", "ping", "playerState", "playerScene", "playerInstance", "playerIFF", "playerColor", "batchedPacket", "clientDisconnect"}
REGISTRY_NAMES = re.compile(r"Object|IDConfirm|UpToDate|UpdateRequest|ConnectSync|RegisterCustomPacket", re.I)

rows = []
for i in sorted(enum):
    name = enum[i]
    h = table.get(i)
    b = method_body(h) if h else None
    code = [l for l in (b or "").splitlines() if l.strip() and not l.strip().startswith("//") and "Mod.Log" not in l]
    sends = sorted(set(re.findall(r"ServerSend\.(\w+)", b or "")))
    reg = bool(re.search(r"Server\.objects|Tracked\w*Data\b", b or ""))
    tnh = bool(re.search(r"TNH", b or "")) or name.startswith("TNH")
    local = bool(re.search(r"\.physical\w*|Patch\.|\bGM\.|\.Instantiate\(", b or ""))
    if name in IMPLEMENTED: cat = "1-done"
    elif h is None: cat = "0-unused"
    elif REGISTRY_NAMES.search(name) or REGISTRY_NAMES.search(h): cat = "2-object registry"
    elif tnh: cat = "5-TNH"
    elif sends and reg: cat = "3-relay, routed by object"
    elif sends: cat = "4-relay, simple"
    else: cat = "6-other"
    rows.append((i, name, h, cat, len(code), reg, tnh, local, sends))

cnt = collections.Counter(r[3] for r in rows)
lines = ["# Upstream handler analysis (generated)", "",
         "Generated by `tools/analyze-handlers.py`. Do not edit by hand.", "",
         "Heuristic classification of each client->server packet by what its upstream handler touches.",
         "*Host-local* = the handler also applies the effect to the host's own game objects "
         "(`.physical`, patches, `GM.`); that half disappears on a dedicated server, leaving the relay.", "",
         "## Summary", "", "| Category | Packets |", "|---|---|"]
lines += [f"| {c.split('-',1)[1]} | {n} |" for c, n in sorted(cnt.items())]
lines += [f"| **total** | **{len(rows)}** |", ""]
for c in sorted(cnt):
    lines += [f"## {c.split('-',1)[1]} ({cnt[c]})", "", "| ID | Packet | Handler | Code lines | Registry | Host-local | ServerSend calls |", "|---|---|---|---|---|---|---|"]
    for r in rows:
        if r[3] == c:
            lines.append(f"| {r[0]} | `{r[1]}` | {r[2] or '-'} | {r[4]} | {'yes' if r[5] else ''} | {'yes' if r[7] else ''} | {', '.join(r[8])} |")
    lines.append("")
out.write_text("\n".join(lines), encoding="utf-8")
for c in sorted(cnt): print(f"{cnt[c]:4d}  {c.split('-',1)[1]}")
print(f"{len(rows):4d}  total  -> {out}")
