#!/usr/bin/env python3
"""Generate Protocol/PacketIds.generated.cs from upstream H3MP's Packet.cs.

Usage: python3 tools/gen-protocol.py <path/to/H3MP/src/networking/Packet.cs> [out.cs]

Copies the ServerPackets/ClientPackets enums verbatim so packet IDs can never
drift from the mod version you are targeting. Re-run when upstream changes.
"""
import re, sys, pathlib

src = pathlib.Path(sys.argv[1]).read_text(encoding="utf-8-sig")
out = pathlib.Path(sys.argv[2] if len(sys.argv) > 2 else
                   "src/H3MP.DedicatedServer/Protocol/PacketIds.generated.cs")

start = src.index("public enum ServerPackets")
start = src.rfind("\n", 0, start) + 1
end = src.index("public class Packet")
end = src.rfind("\n", 0, end) + 1
body = src[start:end]
# drop a trailing /// <summary> block that belongs to class Packet
body = re.sub(r"(\n\s*///[^\n]*)+\s*$", "\n", body)

header = """// <auto-generated>
// Generated by tools/gen-protocol.py from upstream H3MP src/networking/Packet.cs.
// Do not edit by hand. Upstream is GPLv3 (https://github.com/TommySoucy/H3MP).
// </auto-generated>
#pragma warning disable
namespace H3MP.DedicatedServer.Protocol
{
"""
out.write_text(header + body.rstrip() + "\n}\n", encoding="utf-8")
print(f"wrote {out} ({len(re.findall(r'^\s+[A-Za-z0-9_]+ = \d+,?', body, re.M))} enum members)")
